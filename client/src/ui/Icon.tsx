export type IconName = keyof typeof ICON_MAP;

export interface AppIconProps {
  name: IconName;
  size?: number;
  color?: string;
  strokeWidth?: number;
  fill?: string;
  style?: StyleProp<ViewStyle>;
}

/**
 * Primitivo único de iconografía del proyecto Yewi, basado imperativamente en `lucide-react-native`.
 */
export function AppIcon({
  name,
  size = 20,
  color = '#0F172A',
  strokeWidth = 2,
  fill = 'none',
  style,
}: AppIconProps) {
  const IconComponent = ICON_MAP[name] ?? Circle;
  return (
    <IconComponent
      size={size}
      color={color}
      strokeWidth={strokeWidth}
      fill={fill}
      style={style}
    />
  );
}
